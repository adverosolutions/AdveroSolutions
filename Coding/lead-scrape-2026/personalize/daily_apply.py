#!/usr/bin/env python3
"""Local QA/export by default. --write-sheet requires every exported line reviewed.

No approval list can suppress structural/factual failures. human_review.json maps
lead ids to digests copied by the human reviewer from review.json after reading
both line and evidence. It is never generated by this program.
"""
import argparse
import csv
import json
from datetime import datetime
from pathlib import Path
from current import ROOT, digest, evaluate, history, read_json

BDIR = None


def load(bdir):
    selections = {s['lead_id']: s for s in read_json(bdir / 'select.json', [])}
    lines = {r['lead_id']: r.get('icebreaker', '') for r in read_json(bdir / 'lines.json', [])}
    return selections, lines


def all_flags(selections, lines, xs=None):
    if BDIR is None:
        raise ValueError('batch directory is required for source verification')
    leads = {l['lead_id']: l for l in read_json(BDIR / 'leads.json', [])}
    return evaluate(BDIR, leads, selections, xs or {}, lines, history(BDIR))


def apply_approvals(flags, bdir):
    # Retained for callers; old approved.json files never bypass the current gate.
    return flags


def review(bdir):
    selections, lines = load(bdir)
    records = read_json(bdir / 'x.json', {})
    leads = {l['lead_id']: l for l in read_json(bdir / 'leads.json', [])}
    flags = evaluate(bdir, leads, selections, records, lines, history(bdir))
    approvals = read_json(bdir / 'human_review.json', {})
    rows = []
    for lid, selection in selections.items():
        rec, line = records.get(lid, {}), lines.get(lid, '')
        token = digest(rec, line)
        status = 'skipped' if selection['tier'] == 'skip' or flags.get(lid, '').startswith('skipped:') else 'held' if lid in flags else 'reviewed' if approvals.get(lid) == token else 'needs_review'
        rows.append({'lead_id': lid, 'company_name': selection.get('company_name', ''),
                     'mode': rec.get('mode', ''), 'status': status, 'reason': flags.get(lid, ''),
                     'personalization': line, 'record': rec, 'review_digest': token})
    return rows


def export(bdir, rows, destination):
    selections, _ = load(bdir)
    fields = ['lead_id', 'campaign', 'send_order', 'first_name', 'company_name',
              'personalization', 'specialty', 'tier', 'mode', 'x_evidence', 'specific_evidence', 'review_status']
    with destination.open('w', encoding='utf-8-sig', newline='') as handle:
        writer = csv.DictWriter(handle, fieldnames=fields); writer.writeheader()
        for row in rows:
            if row['status'] != 'reviewed':
                continue
            s, rec = selections[row['lead_id']], row['record']
            data = {k: s.get(k, '') for k in fields}
            data.update(personalization=row['personalization'], specialty=rec.get('specialty', ''),
                        tier=2 if rec['mode'] == 'researched' else 1, mode=rec['mode'],
                        x_evidence=json.dumps(rec.get('x_evidence', {})),
                        specific_evidence=json.dumps(rec.get('specific_evidence', {})), review_status='reviewed')
            writer.writerow(data)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('batch', type=Path)
    parser.add_argument('--write-sheet', action='store_true', help='explicit live Sheets apply after authorization')
    args = parser.parse_args()
    bdir = args.batch
    rows = review(bdir)
    (bdir / 'review.json').write_text(json.dumps(rows, indent=2))
    export(bdir, rows, bdir / 'reviewed.csv')
    from collections import Counter
    print('[review] {} -> review.json; reviewed.csv (reviewed rows only)'.format(dict(Counter(r['status'] for r in rows))))
    if not args.write_sheet:
        return
    if any(r['status'] not in ('reviewed', 'skipped') for r in rows):
        raise SystemExit('Refusing Sheets apply: unresolved QA or human review remains')
    # Import live dependencies only after the local validation path finishes.
    import gspread
    from sheet_io import open_tab
    ws = open_tab('1OWJP1WZIFXUi6fIx_QgeUU-KmLqiK5ZsRo2O61BWsMw')
    header = {h: i + 1 for i, h in enumerate(ws.row_values(1))}
    selections, _ = load(bdir)
    updates = []
    for row in rows:
        s = selections[row['lead_id']]
        values = {'icebreaker': row['personalization'] if row['status'] == 'reviewed' else '',
                  'personalization_status': 'done' if row['status'] == 'reviewed' else 'skipped: ' + (row['reason'] or s['angle']),
                  'angle': row['mode'], 'research_notes': json.dumps(row['record'], ensure_ascii=False),
                  'personalized_at': datetime.now().isoformat(timespec='minutes'),
                  'specialty': row['record'].get('specialty', '')}
        for key, value in values.items():
            if key in header:
                updates.append({'range': gspread.utils.rowcol_to_a1(s['sheet_row'], header[key]), 'values': [[value]]})
    for i in range(0, len(updates), 400):
        ws.batch_update(updates[i:i + 400])
    outdir = ROOT / 'output/daily'; outdir.mkdir(exist_ok=True)
    export(bdir, rows, outdir / ('day_' + bdir.name + '.csv'))
    print('[apply] sheet updated; reviewed day CSV exported')


if __name__ == '__main__':
    main()
